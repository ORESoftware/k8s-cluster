#!/usr/bin/env node

import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const serviceDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = resolve(serviceDir, 'generated/api-docs.json');
const outputPath = resolve(serviceDir, 'src/generated/public-openapi.ts');
const checkOnly = process.argv.includes('--check');

const source = await readFile(inputPath, 'utf8');
const document = JSON.parse(source);

if (document.openapi !== '3.1.0') {
  throw new Error(`${inputPath} must be OpenAPI 3.1.0`);
}
if (document['x-dd-contract-scope'] !== 'public') {
  throw new Error(`${inputPath} must be the fail-closed public contract`);
}
for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
  for (const method of ['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace']) {
    const operation = pathItem?.[method];
    if (!operation) continue;
    if (operation['x-dd-visibility'] !== 'public') {
      throw new Error(`${method.toUpperCase()} ${path} is not explicitly public`);
    }
    if (JSON.stringify(operation.security ?? []) !== '[]') {
      throw new Error(`${method.toUpperCase()} ${path} must have an empty public security requirement`);
    }
  }
}

const output = `// Generated by scripts/embed-public-api-docs.mjs. Do not edit.\n` +
  `export const PUBLIC_OPENAPI_JSON = ${JSON.stringify(source)};\n`;

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => null);
  if (current !== output) {
    throw new Error(`${outputPath} is stale; run pnpm docs:embed`);
  }
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output);
}
