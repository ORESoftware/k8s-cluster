import { isNullable, isStringEnum } from './generate.mjs';

const BANNER = 'AUTOGENERATED by src/generate-quote-dart.mjs — do not edit by hand; edit schema/ and regenerate.';
const refName = (schema) => schema?.$ref?.split('/').pop() ?? null;
const nonNull = (schema) => isNullable(schema)
  ? { ...schema, type: schema.type.find((type) => type !== 'null') }
  : schema;
const camel = (value) => value.replace(/[_-]([a-z0-9])/g, (_, character) => character.toUpperCase());

function typeOf(schema) {
  const normalized = nonNull(schema);
  const ref = refName(normalized);
  if (ref) return ref;
  if (isStringEnum(schema) || normalized.type === 'string') return 'String';
  if (normalized.type === 'integer') return 'int';
  if (normalized.type === 'number') return 'double';
  if (normalized.type === 'boolean') return 'bool';
  if (normalized.type === 'array') return `List<${typeOf(normalized.items)}>`;
  return 'Map<String, Object?>';
}

function decode(schema, expression) {
  const normalized = nonNull(schema);
  const ref = refName(normalized);
  if (ref) return `${ref}.fromJson((${expression} as Map).cast<String, Object?>())`;
  if (isStringEnum(schema) || normalized.type === 'string') return `${expression} as String`;
  if (normalized.type === 'integer') return `${expression} as int`;
  if (normalized.type === 'number') return `(${expression} as num).toDouble()`;
  if (normalized.type === 'boolean') return `${expression} as bool`;
  if (normalized.type === 'array') {
    const itemRef = refName(normalized.items);
    return itemRef
      ? `(${expression} as List).map((value) => ${itemRef}.fromJson((value as Map).cast<String, Object?>())).toList(growable: false)`
      : `(${expression} as List).cast<${typeOf(normalized.items)}>()`;
  }
  return `(${expression} as Map).cast<String, Object?>()`;
}

function encode(schema, expression) {
  const normalized = nonNull(schema);
  const ref = refName(normalized);
  if (ref) return `${expression}.toJson()`;
  if (normalized.type === 'array' && refName(normalized.items)) {
    return `${expression}.map((value) => value.toJson()).toList(growable: false)`;
  }
  return expression;
}

export function emitQuoteDart(types) {
  const quoteTypes = types.filter((type) => type.name.startsWith('Quote'));
  const output = [`// ${BANNER}`, ''];

  for (const type of quoteTypes) {
    output.push(`final class ${type.name} {`);
    output.push(`  const ${type.name}({${type.props.map((property) => `${property.required ? 'required ' : ''}this.${camel(property.name)}`).join(', ')}});`);
    for (const property of type.props) {
      output.push(`  final ${typeOf(property.schema)}${property.required && !isNullable(property.schema) ? '' : '?'} ${camel(property.name)};`);
    }

    output.push(`  factory ${type.name}.fromJson(Map<String, Object?> json) => ${type.name}(`);
    for (const property of type.props) {
      const expression = `json['${property.name}']`;
      output.push(`    ${camel(property.name)}: ${property.required ? decode(property.schema, expression) : `${expression} == null ? null : ${decode(property.schema, expression)}`},`);
    }
    output.push('  );', '  Map<String, Object?> toJson() => {');
    for (const property of type.props) {
      const identifier = camel(property.name);
      const encoded = encode(property.schema, property.required ? identifier : `${identifier}!`);
      output.push(`    ${property.required ? '' : `if (${identifier} != null) `}'${property.name}': ${encoded},`);
    }
    output.push('  };', '}', '');
  }

  return {
    'dart/lib/quote_v1.dart': output.join('\n'),
    'dart/pubspec.yaml': "name: canonical_interfaces\ndescription: Generated quote v1 payloads for canonical.plus.\nversion: 0.1.0\npublish_to: none\nenvironment:\n  sdk: '>=3.8.0 <4.0.0'\n",
  };
}
